using System.Text.RegularExpressions;

namespace RepoGuards.Tests;

/// <summary>
/// DESIGN.md §2 and §10 (W8.8): the drawing media come from one engine, Storyworthtelling.Materials, and the tab
/// glyphs are its one approved set. Before this the glyphs were hand-made in three styles (solid fills, 1.6 strokes,
/// 1.8 strokes on a 26 grid), the paper grain was generated three times by three hand-kept copies of one
/// algorithm, and the MAUI apps' pages carried no grain at all.
/// </summary>
public partial class MaterialsAreOneEngineTests
{
    private static readonly string[] Heads =
    [
        "FocusPhone/Codex.Ui.Android", "FocusPhone/Flyleaf.Android", "FocusPhone/Score.Android", "FocusPhone/Post.Android",
        "FocusPhone/Plate.Android", "Pulp/Pulp.Android", "Constitution/Constitution.Android", "Ledger/Ledger.Android",
        "Storyboarder/Folio.Android", "Foreword/Foreword.Android", "Storyworthtelling.Maui",
    ];

    [Fact]
    public void NoTabGlyphIsDrawnByHand()
    {
        var found = Files(Heads, "*.cs")
            .SelectMany(file => File.ReadLines(file).Select((line, i) => (file, line, i)))
            .Where(hit => HandGlyph().IsMatch(hit.line))
            .Select(hit => $"{Relative(hit.file)}:{hit.i + 1}")
            .ToList();
        Assert.True(found.Count == 0, "Take the glyph from Storyworthtelling.Materials.TabGlyphs:\n" + string.Join("\n", found));
    }

    [Fact]
    public void NoHeadKeepsAHandMadeGlyphDrawable()
    {
        var found = Files(Heads, "*.xml")
            .Where(path => path.Replace('\\', '/').Contains("/Resources/drawable", StringComparison.Ordinal))
            .Where(path => GlyphDrawableName().IsMatch(Path.GetFileName(path)))
            .Where(path => !File.ReadAllText(path).Contains("Generated by Tools/IconStudio", StringComparison.Ordinal))
            .Select(Relative)
            .ToList();
        Assert.True(found.Count == 0, "A glyph drawable is IconStudio's, from TabGlyphs:\n" + string.Join("\n", found));
    }

    [Theory]
    [InlineData("FocusPhone/Codex.Ui.Android/PencilGlyphDrawable.cs")]
    [InlineData("Storyworthtelling.Maui/Views/BinderTabs.cs")]
    public void BothStripsDrawTheirGlyphsInPencil(string file) =>
        Assert.Contains("MaterialPainters.PencilGlyph(", Read(file), StringComparison.Ordinal);

    [Theory]
    [InlineData("Storyworthtelling.Maui/Views/PaperBinderPage.cs")]
    [InlineData("Storyworthtelling.Maui/Views/BinderTabs.cs")]
    public void TheMauiGroundsCarryThePaperGrain(string file) =>
        Assert.Contains("PaperGround", Read(file), StringComparison.Ordinal);

    [Theory]
    [InlineData("Storyworthtelling.Paper/PaperGrain.cs")]
    [InlineData("Tools/IconStudio/GrainTile.cs")]
    public void ThePaperGrainIsGeneratedOnce(string file)
    {
        var text = Read(file);
        Assert.Contains("PaperGrainTile.Build()", text, StringComparison.Ordinal);
        Assert.DoesNotContain("XorShift", text, StringComparison.Ordinal);
    }

    private static readonly string[] NativeHeads =
    [
        "FocusPhone/Flyleaf.Android", "FocusPhone/Score.Android", "FocusPhone/Post.Android", "FocusPhone/Plate.Android",
        "Pulp/Pulp.Android", "Constitution/Constitution.Android",
    ];

    /// <summary>The native kit's components draw in the approved media (W8.8 PR 2a).</summary>
    [Theory]
    [InlineData("FocusPhone/Codex.Ui.Android/PaperUi.cs", "new MarkerFillDrawable(")]
    [InlineData("FocusPhone/Codex.Ui.Android/PaperUi.cs", "new PencilOutlineDrawable(")]
    [InlineData("FocusPhone/Codex.Ui.Android/PaperUi.cs", "new HighlighterDrawable(")]
    [InlineData("FocusPhone/Codex.Ui.Android/PaperUi.cs", "new PaperCardDrawable(")]
    [InlineData("FocusPhone/Codex.Ui.Android/Checkbox.cs", "MaterialPainters.Pencil(")]
