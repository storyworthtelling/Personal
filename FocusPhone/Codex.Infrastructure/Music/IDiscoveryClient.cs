using Codex.Domain.Music;

namespace Codex.Infrastructure.Music;

/// <summary>A model-chosen playlist before resolution: a title and the track ids Claude picked.</summary>
public sealed record DiscoverySelection(string Title, IReadOnlyList<string> TrackIds)
{
    public static DiscoverySelection Empty { get; } = new(string.Empty, []);
}

/// <summary>
/// The Claude-backed Discovery engine: given the Taste Profile and the catalog, it picks a playlist. Kept an
/// interface so it can be faked in tests and no-op'd without a key. The caller resolves the returned ids to
/// real tracks with <see cref="PlaylistPlan"/>, so a hallucinated id never reaches the player.
/// </summary>
public interface IDiscoveryClient
{
    /// <summary>Picks a playlist for a prompted request (a mood/genre/free-text seed).</summary>
    Task<DiscoverySelection> GeneratePlaylistAsync(
        TasteProfile profile, IReadOnlyList<Track> catalog, PlaylistRequest request, CancellationToken cancellationToken);

    /// <summary>
    /// Picks the weekly "New for you" set — the crate, generated by the Friday worker.
    /// </summary>
    /// <param name="note">
    /// Something measured about the library that the pick should answer — today, the
    /// tempo the workout ran short of. A measurement, never a preference: it says
    /// "there is not enough music at this speed", which is a fact about the shelf
    /// rather than a rating, so it can cross over without the workout teaching the
    /// taste profile anything.
    /// </param>
    /// <param name="owned">
    /// What the listener already has. Evidence of taste and an <b>exclusion list</b> —
    /// never the source. The crate exists to name records that are not on the shelf,
    /// so a pick drawn from this is the one thing it must not return.
    /// </param>
    /// <param name="subscribedShows">
    /// Podcast shows already followed, by title — the podcast side's equivalent of
    /// <paramref name="owned"/>, so a show pick can be excluded the same way a track or album
    /// already on the shelf is.
    /// </param>
    Task<IReadOnlyList<Recommendation>> WeeklyDiscoveriesAsync(
        TasteProfile profile, IReadOnlyList<Track> owned, int maxTracks,
        string? note, IReadOnlyList<string> subscribedShows, CancellationToken cancellationToken);
}
