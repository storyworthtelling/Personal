using System.Globalization;
using Storyworthtelling.Materials;

namespace IconStudio;

/// <summary>
/// The few tab glyphs Android needs as a drawable resource rather than drawn in pencil by a kit: a notification's
/// small icon, which the system draws as a white silhouette of whatever it is given. Written from
/// <see cref="TabGlyphs"/> so a notification and a tab cannot drift apart. Never hand-edit the output.
/// </summary>
public static class GlyphDrawables
{
    /// <summary>Each resource IconStudio writes, and the glyph it draws.</summary>
    public static IReadOnlyList<(string Path, string Glyph)> Targets { get; } =
    [
        ("FocusPhone/Post.Android/Resources/drawable/glyph_mailbox.xml", nameof(TabGlyphs.Mailbox)),
        ("FocusPhone/Score.Android/Resources/drawable/glyph_note.xml", nameof(TabGlyphs.Note)),
    ];

    public static string Render(string glyph)
    {
        var data = TabGlyphs.All[glyph];
        var size = TabGlyphs.Viewport.ToString(CultureInfo.InvariantCulture);
        var stroke = TabGlyphs.StrokeWidth.ToString(CultureInfo.InvariantCulture);
        return $"""
            <?xml version="1.0" encoding="utf-8"?>
            <!-- Generated by Tools/IconStudio from Storyworthtelling.Materials.TabGlyphs.{glyph} (DESIGN.md §10). Do not edit. -->
            <vector xmlns:android="http://schemas.android.com/apk/res/android"
                android:width="{size}dp"
                android:height="{size}dp"
                android:viewportWidth="{size}"
                android:viewportHeight="{size}">
                <path
                    android:pathData="{data}"
                    android:fillColor="#00000000"
                    android:strokeColor="#FFFFFFFF"
                    android:strokeWidth="{stroke}"
                    android:strokeLineCap="round"
                    android:strokeLineJoin="round" />
            </vector>

            """;
    }

    public static IReadOnlyList<string> Write(string repoRoot)
    {
        var written = new List<string>();
        foreach (var (target, glyph) in Targets)
        {
            var path = Path.Combine(repoRoot, target.Replace('/', Path.DirectorySeparatorChar));
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, Render(glyph));
            written.Add(path);
        }
        return written;
    }
}
