namespace LogLoopReader.Tests;

// §6.3: a claude/logfix-* PR auto-merges when — and only when — it really is a log-derived bug fix: every
// fingerprint is a Fix in a report issue, every commit names one, and each fix has its test first. Green
// tests and the leak guard (conditions 5 and 6) are branch protection's job, which this gate leaves to it.
public class AutoMergeGateTests
{
    private const string Fp1 = "1111111111111111111111111111111111111111111111111111111111111111";
    private const string Fp2 = "2222222222222222222222222222222222222222222222222222222222222222";
    private const string Owner = "invented-owner";

    private static string Block(string fingerprint) =>
        $"<!-- log-loop\nfingerprint: {fingerprint}\nclass: C13\nsource: swt-log.post.a1b2c3d4e5f6.000001-000004.json\noccurrences: 14\nphones: owner\nfirst-seen: 2026-10-24\n-->";

    private static ReportIssue Report(string author = Owner, params string[] fixes) => new(
        "Log loop — week of 2026-11-08", author,
        "Counts…\n<!-- log-loop-report\nweek: 2026-11-08\n" + string.Join("\n", fixes.Select(f => "fix: " + f)) + "\n-->\n---\n_Generated by [Claude Code](https://claude.ai/code)_");

    private static GateCommit Commit(string sha, string? fingerprint, params string[] files) =>
        new(sha, "Fix something\n\n" + (fingerprint is null ? string.Empty : $"Log-Loop-Fingerprint: {fingerprint}\n"), files, 1);

    private static GateInput Input(
        IReadOnlyList<GateCommit>? commits = null, string? body = null, IReadOnlyList<ReportIssue>? reports = null,
        string branch = "claude/logfix-2026-11-08-post", bool fork = false, string author = Owner) => new(
        branch, fork, author, [Owner], body ?? Block(Fp1),
        commits ?? [Commit("a1", Fp1, "FocusPhone/Codex.Tests/Post/MailboxTests.cs"), Commit("b2", Fp1, "FocusPhone/Post.Android/MailboxArea.cs")],
        reports ?? [Report(Owner, Fp1)]);

    [Fact]
    public void AFullyTaggedPrWithItsTestFirstPasses()
    {
        var decision = AutoMergeGate.Decide(Input());

        Assert.True(decision.Enable, string.Join("; ", decision.Reasons));
    }

    [Fact]
    public void ACommitWithoutATrailerHoldsThePr()
    {
        var decision = AutoMergeGate.Decide(Input(commits:
        [
            Commit("a1", Fp1, "FocusPhone/Codex.Tests/Post/MailboxTests.cs"),
            Commit("b2", Fp1, "FocusPhone/Post.Android/MailboxArea.cs"),
            Commit("c3", null, "FocusPhone/Post.Android/SettingsArea.cs"),
        ]));

        Assert.False(decision.Enable);
        Assert.Contains(decision.Reasons, r => r.Contains("c3"));
    }

    [Fact]
    public void AnUnknownFingerprintHolds()
    {
        var decision = AutoMergeGate.Decide(Input(commits:
        [
            Commit("a1", Fp2, "FocusPhone/Codex.Tests/Post/MailboxTests.cs"),
            Commit("b2", Fp2, "FocusPhone/Post.Android/MailboxArea.cs"),
        ]));

        Assert.False(decision.Enable);
    }

    [Fact]
    public void AFingerprintTheReportDidNotMarkFixHolds()
    {
        var decision = AutoMergeGate.Decide(Input(reports: [Report(Owner, Fp2)]));

        Assert.False(decision.Enable);
        Assert.Contains(decision.Reasons, r => r.Contains("not marked Fix"));
    }

    [Fact]
    public void NoReportYetHolds()
    {
        Assert.False(AutoMergeGate.Decide(Input(reports: [])).Enable);
    }

    [Fact]
    public void AReportByAnyoneElseDoesNotCount()
    {
        Assert.False(AutoMergeGate.Decide(Input(reports: [Report("someone-else", Fp1)])).Enable);
    }

    [Fact]
    public void AFixWithoutAPrecedingTestCommitHolds()
    {
        var fixFirst = AutoMergeGate.Decide(Input(commits:
        [
            Commit("a1", Fp1, "FocusPhone/Post.Android/MailboxArea.cs"),
            Commit("b2", Fp1, "FocusPhone/Codex.Tests/Post/MailboxTests.cs"),
        ]));
        var noTest = AutoMergeGate.Decide(Input(commits: [Commit("b2", Fp1, "FocusPhone/Post.Android/MailboxArea.cs")]));

        Assert.False(fixFirst.Enable);
        Assert.False(noTest.Enable);
        Assert.Contains(fixFirst.Reasons, r => r.Contains("test"));
    }

    [Fact]
    public void TwoFixesEachNeedTheirOwnTestFirst()
    {
        var decision = AutoMergeGate.Decide(Input(
            body: Block(Fp1) + "\n" + Block(Fp2),
            reports: [Report(Owner, Fp1, Fp2)],
            commits:
            [
                Commit("a1", Fp1, "FocusPhone/Codex.Tests/Post/MailboxTests.cs"),
                Commit("b2", Fp1, "FocusPhone/Post.Android/MailboxArea.cs"),
                Commit("c3", Fp2, "FocusPhone/Post.Android/SettingsArea.cs"),
            ]));

        Assert.False(decision.Enable);
    }

    [Fact]
    public void AFingerprintInTheBodyWithNoCommitHolds()
    {
        var decision = AutoMergeGate.Decide(Input(body: Block(Fp1) + "\n" + Block(Fp2), reports: [Report(Owner, Fp1, Fp2)]));

        Assert.False(decision.Enable);
    }

    [Fact]
    public void AnyOtherBranchAForkOrAnotherAuthorHolds()
    {
        Assert.False(AutoMergeGate.Decide(Input(branch: "claude/some-feature")).Enable);
        Assert.False(AutoMergeGate.Decide(Input(fork: true)).Enable);
        Assert.False(AutoMergeGate.Decide(Input(author: "someone-else")).Enable);
    }

    [Fact]
    public void AMergeCommitHolds()
    {
        var decision = AutoMergeGate.Decide(Input(commits:
        [
            Commit("a1", Fp1, "FocusPhone/Codex.Tests/Post/MailboxTests.cs"),
            Commit("b2", Fp1, "FocusPhone/Post.Android/MailboxArea.cs"),
            new GateCommit("m3", "Merge main\n\nLog-Loop-Fingerprint: " + Fp1, ["x.cs"], 2),
        ]));

        Assert.False(decision.Enable);
    }

    [Fact]
    public void AReportFromAnEarlierWeekThanTheBranchDoesNotCount()
    {
        var old = new ReportIssue("Log loop — week of 2026-11-01", Owner, "<!-- log-loop-report\nweek: 2026-11-01\nfix: " + Fp1 + "\n-->");

        Assert.False(AutoMergeGate.Decide(Input(reports: [old])).Enable);
    }

    [Fact]
    public void ALaterWeeksReportCountsForABranchStillOpenFromBefore()
    {
        var later = new ReportIssue("Log loop — week of 2026-11-15", Owner, "<!-- log-loop-report\nweek: 2026-11-15\nfix: " + Fp1 + "\n-->");

        Assert.True(AutoMergeGate.Decide(Input(reports: [later])).Enable);
    }

    [Fact]
    public void TheGateReadsItsInputFromJson()
    {
        const string json = """
        {"branch":"claude/logfix-2026-11-08-post","fromFork":false,"prAuthor":"invented-owner","trustedAuthors":["invented-owner"],
         "body":"<!-- log-loop\nfingerprint: 1111111111111111111111111111111111111111111111111111111111111111\n-->",
         "commits":[{"sha":"a1","message":"t\n\nLog-Loop-Fingerprint: 1111111111111111111111111111111111111111111111111111111111111111","files":["X.Tests/ATests.cs"],"parents":1},
                    {"sha":"b2","message":"f\n\nLog-Loop-Fingerprint: 1111111111111111111111111111111111111111111111111111111111111111","files":["X/A.cs"],"parents":1}],
         "reports":[{"title":"Log loop — week of 2026-11-08","author":"invented-owner","body":"<!-- log-loop-report\nweek: 2026-11-08\nfix: 1111111111111111111111111111111111111111111111111111111111111111\n-->"}]}
        """;

        Assert.True(AutoMergeGate.Decide(GateInput.FromJson(json)).Enable);
    }
}
